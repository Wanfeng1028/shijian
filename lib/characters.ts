/**
 * 历史数字人物定义（沉浸对话 / 角色扮演）。
 *
 * 来源：与 Coze 版史鉴同一批人物（孔子、秦始皇、商鞅、张骞、王安石、林则徐）加
 * 新增内置人物（司马迁、魏源、孙中山），共 9 位；锚点全部取自人教版高中历史
 * 教材（《中外历史纲要（上/下）》及 RAG 语料 chunks.json），每条锚点均可追溯到具体 chunk。
 * source 区分内置（builtin）与用户自定义（custom）；自定义人物设计见 custom-characters.md。
 * 本文件只含公开的教材事实，不含密钥；前端可直接 import，/api/characters 亦由此取数。
 *
 * 铁律（与 roleplay-prompt.md 一致）：
 * - 人物只说自己生前可能知道的事，死后之事一律不知道；
 * - 人物不得引用自己死后才成书的文献（如《史记》），可说的原话只说内容本身，
 *   出处由系统在核对时标注，不由人物自己说出；
 * - 除 anchors 中注明出处的引文外，一律不得编造人物原话、文献与出处。
 */

export interface FigureAnchor {
  /** 锚点标题，如“商鞅变法” */
  label: string;
  /** 教材/史料出处，如“《中外历史纲要（上）·商鞅变法” */
  source: string;
  /** 一句话事实说明 */
  note: string;
  /** 可引用的原话（必须真实可查）；无则不填，人物只能转述 */
  quote?: string;
}

export interface HistoricalFigure {
  id: string;
  /** 内置人物（builtin）或用户自定义人物（custom）；自定义见 custom-characters.md */
  source: 'builtin' | 'custom';
  name: string;
  /** 朝代 / 时期 */
  era: string;
  /** 生卒年 */
  lifespan: string;
  /** 身份 */
  role: string;
  /** 口吻 */
  voice: string;
  /** 面板上的一句话介绍 */
  intro: string;
  /** 进入对话时的开场白（第一人称，推想口吻，100 字以内） */
  greeting: string;
  /** 知识截止：人物所知止于哪一年 */
  knowledgeCutoff: string;
  /** 明确不知道的事（死后之事） */
  cannotKnow: string[];
  /** 课本锚点：2–3 条 */
  anchors: FigureAnchor[];
  /** 绝不越过的线 */
  neverCross: string[];
  /** 快捷提问 */
  quickQuestions: string[];
}

