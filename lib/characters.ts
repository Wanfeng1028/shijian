/** id → 人物，供后端按 id 取卡片。 */
export const CHARACTER_MAP: Record<string, HistoricalFigure> = Object.fromEntries(
  CHARACTERS.map((c) => [c.id, c]),
);

/** 全部人物 id（固定顺序：孔子、秦始皇、商鞅、张骞、王安石、林则徐、司马迁、魏源、孙中山）。 */
export const CHARACTER_IDS: string[] = CHARACTERS.map((c) => c.id);

export function getCharacter(id: unknown): HistoricalFigure | null {
  if (typeof id !== 'string') return null;
  return CHARACTER_MAP[id] ?? null;
}

export function isKnownCharacter(id: unknown): id is string {
  return typeof id === 'string' && id in CHARACTER_MAP;
}

/** 给 /api/characters 返回的公开字段（不含 anchors / neverCross 等提示词内部细节）。 */
export function toPublicCharacter(c: HistoricalFigure) {
  return {
    id: c.id,
    source: c.source,
    name: c.name,
    era: c.era,
    lifespan: c.lifespan,
    role: c.role,
    intro: c.intro,
    greeting: c.greeting,
    quickQuestions: c.quickQuestions,
  };
}
